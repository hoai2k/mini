def render():
    n_assets = sum(len(a[2]) for a in ACTS)
    out = [START, '', '## Part C — Acts II to V and the shared cast', '',
           f'The rest of the game, designed in [`acts.md`](acts.md): {n_assets} game assets and '
           f'{len(MOODS)} mood boards. Every prompt below is complete; paste it as it stands. Sizes are '
           f'2× game units, as in Part B. Name each file by its id (for example `sailor-stand.png`) and '
           f'drop it in [`../intake/`](../intake/README.md). The ids are already listed as `requested` in '
           f'`assets/manifest.json`.', '',
           'Times such as "video 0:25" refer to `references/video-frames/frame-025s.jpg`; attach those frames '
           'as image references when generating. Characters must match the delivered mood boards: the sailor `mood-sailor-1`, the witch '
           '`mood-witch-1`, and the band `band-trio` / `video-cover.jpg`. Generate `mood-beloved` first so '
           'the beloved stays consistent across her three appearances.', '',
           '### C0. Mood boards for the new acts', '', '| Id | Subject | Prompt |', '| --- | --- | --- |']
    for mid, subject, prompt in MOODS:
        out.append(f'| `{mid}` | {subject} | {prompt} |')
    out.append('')
    for i, (title, blurb, items) in enumerate(ACTS, 1):
        out += [f'### C{i}. {title}', '', blurb, '', '| Id | Size | Anchor |', '| --- | --- | --- |']
        out += [f'| `{a[0]}` | {a[2]} × {a[3]} | {a[4]} |' for a in items]
        out.append('')
        for aid, name, w, h, anchor, style, desc in items:
            out += [f'#### `{aid}` — {name}', '', f'{w} × {h} px, anchor {anchor}.', '',
                    f'> {desc[0].upper() + desc[1:]} {style}', '']
    out.append(END)
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv
    doc = open(DOC).read()
    block = render()
    if START in doc:
        new = doc[:doc.index(START)] + block + doc[doc.index(END) + len(END):]
    else:
        new = doc.rstrip('\n') + '\n\n---\n\n' + block + '\n'
    m = json.load(open(MANIFEST))
    slots = m['slots']
    changed = False
    wanted = {aid for _, _, items in ACTS for aid, *_ in items}
    for aid in wanted:
        if aid not in slots:
            slots[aid] = {'status': 'requested', 'file': aid + '.webp'}
            changed = True
    # Requests dropped from the design go too (never a delivered slot).
    for aid in [k for k, v in slots.items() if v.get('status') == 'requested' and k not in wanted]:
        del slots[aid]
        changed = True
    if check:
        if new != doc or changed:
            raise SystemExit('image-requests.md or manifest.json is out of date: rerun build_act_requests.py')
        print('Part C up to date')
        return
    open(DOC, 'w').write(new)
    if changed:
        with open(MANIFEST, 'w') as f:
            json.dump(m, f, indent=2)
            f.write('\n')
    print('wrote Part C:', sum(len(a[2]) for a in ACTS), 'assets,', len(MOODS), 'mood boards')


if __name__ == '__main__':
    main()
