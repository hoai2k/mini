def render():
    out = [START, '', '## Planning images for the film adaptation', '',
           f'Requested 11 October 2026 for [the film adaptation plan](film-adaptation.md): '
           f'{len(CHARACTERS)} canonical character sheets and {len(SCENES)} scene concepts. They are for agreeing '
           'the cast, the look and the staging before the art and code rounds, and are documentation art, not '
           'game files, so they are not in `assets/manifest.json`. Every prompt is complete; paste it as it '
           'stands. Generate the character sheets first and agree on them, then attach the relevant sheets as '
           'image references for each scene so the cast stays consistent. Where a prompt names a file under '
           '`references/expanded-world/`, attach that image too. Name each file by its id (for example '
           '`char-bel-azor.png`) and drop it in [`../intake/`](../intake/README.md); on integration they land in '
           '`references/film-planning/`.', '',
           '### Character sheets', '', 'Each 2400 × 1600 px (landscape).', '',
           '| Id | Character |', '| --- | --- |']
    out += [f'| `{cid}` | {title} |' for cid, title, _ in CHARACTERS]
    out.append('')
    for cid, title, subject in CHARACTERS:
        out += [f'#### `{cid}` — {title}', '', f'> {subject} {SHEET}', '']
    out += ['### Scene concepts', '', 'Each 2560 × 1440 px (16:9).', '', '| Id | Scene |', '| --- | --- |']
    out += [f'| `{sid}` | {title} |' for sid, title, _ in SCENES]
    out.append('')
    for sid, title, subject in SCENES:
        out += [f'#### `{sid}` — {title}', '', f'> {subject} {SCENE}', '']
    out.append(END)
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv
    doc = open(DOC).read()
    block = render()
    if START in doc:
        new = doc[:doc.index(START)] + block + doc[doc.index(END) + len(END):]
    else:
        assert ANCHOR in doc, f'{ANCHOR!r} not found in image-requests.md'
        i = doc.index(ANCHOR)
        new = doc[:i] + block + '\n\n' + doc[i:]
    if check:
        if new != doc:
            raise SystemExit('image-requests.md is out of date: rerun build_film_requests.py')
        print('Film planning requests up to date')
        return
    open(DOC, 'w').write(new)
    print('wrote film planning requests:', len(CHARACTERS), 'character sheets,', len(SCENES), 'scene concepts')


if __name__ == '__main__':
    main()
