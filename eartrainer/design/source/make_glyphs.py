#!/usr/bin/env python3
"""Extract the music glyphs the staff draws (clefs, accidentals, notehead) from the
Bravura font as SVG paths, into app/src/glyphs.js.

    pip install fonttools
    python3 eartrainer/design/source/make_glyphs.py

Bravura is by Steinberg Media Technologies, under the SIL Open Font License 1.1
(https://github.com/steinbergmedia/bravura). It follows SMuFL: 1000 units to the
em, one staff space is 250 units, and y points up from the glyph's origin
(the G line for the treble clef, the F line for the bass clef, the note's line or
space for noteheads and accidentals).
"""

import json
import urllib.request
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT.parent / "local" / "eartrainer-datasets" / "Bravura.otf"
URL = "https://raw.githubusercontent.com/steinbergmedia/bravura/master/redist/otf/Bravura.otf"
GLYPHS = {"gClef": 0xE050, "fClef": 0xE062, "flat": 0xE260, "natural": 0xE261, "sharp": 0xE262,
          "doubleSharp": 0xE263, "doubleFlat": 0xE264, "notehead": 0xE0A4}


def main() -> None:
    if not CACHE.exists():
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        CACHE.write_bytes(urllib.request.urlopen(URL).read())
    font = TTFont(CACHE)
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    out = {}
    for name, cp in GLYPHS.items():
        g = glyphs[cmap[cp]]
        pen, bounds = SVGPathPen(glyphs), BoundsPen(glyphs)
        g.draw(pen)
        g.draw(bounds)
        out[name] = {"d": pen.getCommands(), "w": g.width, "bounds": list(bounds.bounds)}
    js = ("// Music glyphs from the Bravura font (Steinberg, SIL Open Font License 1.1), as SVG\n"
          "// paths in font units: 250 units = one staff space, y up from the glyph's origin.\n"
          "// GENERATED by eartrainer/design/source/make_glyphs.py; do not edit by hand.\n"
          f"export default {json.dumps(out, separators=(',', ':'))};\n")
    (ROOT / "app" / "src" / "glyphs.js").write_text(js, encoding="utf-8")
    print("wrote app/src/glyphs.js", len(js), "bytes")


if __name__ == "__main__":
    main()
