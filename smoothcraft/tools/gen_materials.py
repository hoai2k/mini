#!/usr/bin/env python3
"""Generate the shader's material table from materials.json.

    python3 smoothcraft/tools/gen_materials.py          # write the table
    python3 smoothcraft/tools/gen_materials.py --check  # fail if it is out of date

The table is assets/smoothcraft/shaders/include/materials.glsl; a material's
index in materials.json is its index in the table.
"""
import json
import sys
from pathlib import Path

RES = Path(__file__).resolve().parent.parent / "mod" / "src" / "main" / "resources" / "assets" / "smoothcraft"
SOURCE = RES / "materials.json"
TARGET = RES / "shaders" / "include" / "materials.glsl"


def render() -> str:
    materials = json.loads(SOURCE.read_text())["materials"]
    if len(materials) > 255:
        raise SystemExit("at most 255 materials fit in the vertex alpha")
    a = [f"    vec4({m['roughness']:.3f}, {m['metal']:.3f}, {m['f0']:.3f}, {m['subsurface']:.3f})" for m in materials]
    b = [f"    vec4({m['emissive']:.3f}, {m['bump']:.3f}, {m['sheen']:.3f}, {m['wet']:.3f})" for m in materials]
    names = "\n".join(f"#define SMOOTH_MAT_{m['name'].upper()} {i}" for i, m in enumerate(materials))
    n = len(materials)
    return f"""// Generated by smoothcraft/tools/gen_materials.py from assets/smoothcraft/materials.json. Do not edit.
#ifndef SMOOTHCRAFT_MATERIALS_GLSL
#define SMOOTHCRAFT_MATERIALS_GLSL

#define SMOOTH_MATERIAL_COUNT {n}
{names}

// x roughness, y metal, z f0, w subsurface
const vec4 SMOOTH_MATERIAL_A[{n}] = vec4[](
{(","+chr(10)).join(a)}
);

// x emissive, y bump, z sheen, w wet
const vec4 SMOOTH_MATERIAL_B[{n}] = vec4[](
{(","+chr(10)).join(b)}
);

#endif
"""


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            raise SystemExit(f"{TARGET} is out of date: run tools/gen_materials.py")
        print("materials.glsl is up to date")
        return
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text)
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
