// The amoeba world's opening cell, written out for the tardigrade world's
// glimpse of it in the pool (the Tardigrade -> Amoeba transition crossfades
// one into the other, so they must be the same cell). The amoeba world's
// warm-up (main.js: 600 resting steps of the soft body from a disc, seeded)
// is deterministic: this loads the page in headless Chromium with no
// animation frames run, reads the cell as the warm-up leaves it, and writes
// ../shared/amoeba-opening.js (the outline about its centroid, the nucleus
// and the contractile vacuole, in µm, the slide's x right and y up).
//
//   node micro/prototypes/amoeba/opening.mjs          # regenerate
//   node micro/prototypes/amoeba/opening.mjs --check  # fail if it no longer matches
import { createServer } from 'node:http';
import { readFile, writeFile, stat } from 'node:fs/promises';
import { join, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'shared', 'amoeba-opening.js');
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg' };
const server = createServer(async (req, res) => {
  let p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
  if (p.endsWith('/')) p += 'index.html';
  const file = join(root, p);
  try {
    if (!file.startsWith(root) || !(await stat(file)).isFile()) throw new Error();
    res.writeHead(200, { 'content-type': TYPES[extname(file)] || 'application/octet-stream' });
    res.end(await readFile(file));
  } catch { res.writeHead(404); res.end(); }
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const { chromium } = createRequire(join(root, 'check.mjs'))('playwright');
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
let cell;
try {
  const tab = await browser.newPage({ viewport: { width: 800, height: 450 } });
  await tab.addInitScript(() => { window.requestAnimationFrame = () => 0; }); // the warm-up only: no frame runs
  await tab.goto(`http://127.0.0.1:${server.address().port}/amoeba/`, { waitUntil: 'load' });
  await tab.waitForFunction(() => window.__micro && window.__micro.body, null, { timeout: 120000, polling: 500 });
  cell = await tab.evaluate(() => {
    const b = window.__micro.body, c = window.__micro.cyto, r1 = (v) => Math.round(v * 10) / 10;
    const out = [];
    for (let i = 0; i < b.x.length; i++) out.push(r1(b.x[i] - b.cx), r1(b.y[i] - b.cy));
    return {
      area: Math.round(b.A0), outline: out,
      nucleus: { x: r1(c.nucleus.x - b.cx), y: r1(c.nucleus.y - b.cy), r: r1(c.nucleus.r) },
      vacuole: { x: r1(c.cv.x - b.cx), y: r1(c.cv.y - b.cy), r: r1(c.cv.r) },
    };
  });
} finally {
  await browser.close();
  server.close();
}

if (process.argv.includes('--check')) {
  const { OPENING } = await import(OUT + `?t=${Date.now()}`);
  let worst = Math.abs(OPENING.area - cell.area) / 100;
  for (let i = 0; i < cell.outline.length; i++) worst = Math.max(worst, Math.abs(OPENING.outline[i] - cell.outline[i]));
  for (const k of ['nucleus', 'vacuole']) for (const q of ['x', 'y', 'r']) worst = Math.max(worst, Math.abs(OPENING[k][q] - cell[k][q]));
  console.log(`the amoeba world's opening cell is within ${worst.toFixed(1)} µm of shared/amoeba-opening.js`);
  if (worst > 2) { console.error('it has drifted: regenerate it with node micro/prototypes/amoeba/opening.mjs'); process.exit(1); }
} else {
  const rows = [];
  for (let i = 0; i < cell.outline.length; i += 16) rows.push('    ' + cell.outline.slice(i, i + 16).join(', ') + ',');
  await writeFile(OUT, `// GENERATED by micro/prototypes/amoeba/opening.mjs: do not edit by hand.
// The amoeba world's cell as it opens (after its warm-up, amoeba/main.js),
// which the tardigrade world shows on its pool floor (tardigrade/landmarks.js)
// so the transition between the two crossfades one cell into the same cell.
// µm about the cell's centroid, the slide's x to the right and y up the
// screen (the cell's heading in a pose, up the slide); outline: x, y pairs
// round the membrane (anticlockwise).
export const OPENING = {
  area: ${cell.area},
  nucleus: ${JSON.stringify(cell.nucleus).replace(/"/g, '').replace(/[:,]/g, '$& ').replace(/^\{/, '{ ').replace(/\}$/, ' }')},
  vacuole: ${JSON.stringify(cell.vacuole).replace(/"/g, '').replace(/[:,]/g, '$& ').replace(/^\{/, '{ ').replace(/\}$/, ' }')},
  outline: [
${rows.join('\n')}
  ],
};
`);
  console.log(`wrote ${OUT}: ${cell.outline.length / 2} points, area ${cell.area} µm²`);
}
